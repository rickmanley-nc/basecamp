import { parentPort, workerData } from "node:worker_threads";
import { Client } from "pg";

const numericTypeIds = new Set([20, 21, 23, 26, 700, 701, 1700]);
const insertConflictColumns = new Map([
  ["schema_migrations", ["id"]],
  ["seed_imports", ["schema_version"]],
  ["categories", ["id"]],
  ["capability_levels", ["id"]],
  ["quest_templates", ["id"]],
  ["category_pursuits", ["category_id"]],
  ["quest_instances", ["id"]],
  ["quest_events", ["id"]],
  ["drill_templates", ["id"]],
  ["locations", ["id"]],
  ["location_relationships", ["id"]],
  ["location_readiness", ["location_id", "category_id"]],
  ["inventory_items", ["id"]],
  ["inventory_lots", ["id"]],
  ["assets", ["id"]],
  ["xp_events", ["id"]],
  ["evidence_records", ["id"]],
  ["skill_progress", ["skill_id"]],
  ["training_records", ["id"]],
  ["drill_runs", ["id"]],
  ["asset_tags", ["id"]],
  ["kits", ["id"]],
  ["kit_items", ["id"]],
  ["inventory_events", ["id"]],
  ["maintenance_policies", ["id"]],
  ["maintenance_events", ["id"]],
  ["sync_clients", ["client_id"]],
  ["sync_commands", ["command_id"]],
  ["sync_conflicts", ["id"]],
  ["audit_events", ["id"]],
  ["local_users", ["id"]],
  ["auth_sessions", ["id"]]
]);

const client = new Client({
  connectionString: workerData.connectionString,
  ssl: workerData.ssl
});

let connected = false;

parentPort?.on("message", (message) => {
  void handleRequest(message);
});

async function handleRequest(message) {
  const { operation, sql, params, responsePort, signal } = message;

  try {
    const value = await execute(operation, sql, params ?? []);
    responsePort.postMessage({ ok: true, value });
  } catch (error) {
    responsePort.postMessage({
      ok: false,
      error: error instanceof Error ? error.message : "PostgreSQL worker operation failed."
    });
  } finally {
    Atomics.store(signal, 0, 1);
    Atomics.notify(signal, 0);
    responsePort.close();
  }
}

async function execute(operation, sql, params) {
  if (operation === "close") {
    if (connected) {
      await client.end();
      connected = false;
    }

    return undefined;
  }

  await ensureConnected();

  const translated = translateSql(sql, params);

  if (translated.noop) {
    return operation === "run" ? { changes: 0 } : operation === "all" ? [] : undefined;
  }

  const result = await client.query(translated.sql, translated.params);

  if (operation === "exec") {
    return undefined;
  }

  const queryResult = Array.isArray(result) ? result.at(-1) : result;

  if (queryResult === undefined) {
    return operation === "run" ? { changes: 0 } : operation === "all" ? [] : undefined;
  }

  const rows = normalizeRows(queryResult.rows, queryResult.fields);

  if (operation === "all") {
    return rows;
  }

  if (operation === "get") {
    return rows[0];
  }

  if (operation === "run") {
    return { changes: queryResult.rowCount ?? 0 };
  }

  throw new Error(`Unknown PostgreSQL worker operation ${operation}.`);
}

async function ensureConnected() {
  if (!connected) {
    await client.connect();
    connected = true;
  }
}

function translateSql(sql, params) {
  const trimmed = sql.trim();

  if (/^PRAGMA\s+foreign_keys\s*=\s*(OFF|ON)\s*;?$/i.test(trimmed)) {
    return { sql: "", params: [], noop: true };
  }

  const tableInfo = trimmed.match(/^PRAGMA\s+table_info\(("?)([A-Za-z_][A-Za-z0-9_]*)\1\)\s*;?$/i);

  if (tableInfo?.[2] !== undefined) {
    return {
      sql: `SELECT column_name AS name
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = $1
            ORDER BY ordinal_position`,
      params: [tableInfo[2]]
    };
  }

  if (/sqlite_master/i.test(trimmed)) {
    return translateSqliteMasterQuery(trimmed, params);
  }

  return {
    sql: replaceQuestionPlaceholders(translateInsertOrReplace(translateMigrationSql(sql))),
    params
  };
}

function translateMigrationSql(sql) {
  return sql
    .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g, "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    .replace(/\bTEXT NOT NULL DEFAULT CURRENT_TIMESTAMP\b/g, "TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)");
}

function translateSqliteMasterQuery(sql, params) {
  if (/name\s+NOT\s+LIKE\s+'sqlite_%'/i.test(sql)) {
    return {
      sql: `SELECT table_name AS name
            FROM information_schema.tables
            WHERE table_schema = 'public'
              AND table_type = 'BASE TABLE'
            ORDER BY table_name`,
      params: []
    };
  }

  return {
    sql: `SELECT table_name AS name
          FROM information_schema.tables
          WHERE table_schema = 'public'
            AND table_type = 'BASE TABLE'
            AND table_name = $1`,
    params
  };
}

function translateInsertOrReplace(sql) {
  const match = sql.match(
    /^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+("?)([A-Za-z_][A-Za-z0-9_]*)\1\s*\(([\s\S]*?)\)\s*VALUES\s*\(([\s\S]*?)\)\s*;?\s*$/i
  );

  if (match === null || match[2] === undefined || match[3] === undefined || match[4] === undefined) {
    return sql;
  }

  const table = match[2];
  const columns = splitCommaList(match[3]);
  const values = splitCommaList(match[4]);
  const conflictColumns = insertConflictColumns.get(table) ?? ["id"];
  const updateColumns = columns
    .map(unquoteIdentifier)
    .filter((column) => !conflictColumns.includes(column));
  const updateClause =
    updateColumns.length === 0
      ? "DO NOTHING"
      : `DO UPDATE SET ${updateColumns
          .map((column) => `${quoteIdentifier(column)} = EXCLUDED.${quoteIdentifier(column)}`)
          .join(", ")}`;

  return `INSERT INTO ${quoteIdentifier(table)} (${columns.join(", ")})
          VALUES (${values.join(", ")})
          ON CONFLICT (${conflictColumns.map(quoteIdentifier).join(", ")}) ${updateClause}`;
}

function replaceQuestionPlaceholders(sql) {
  let index = 0;
  let output = "";
  let inSingleQuote = false;
  let inDoubleQuote = false;

  for (let position = 0; position < sql.length; position += 1) {
    const char = sql[position];
    const next = sql[position + 1];

    if (char === "'" && !inDoubleQuote) {
      output += char;

      if (inSingleQuote && next === "'") {
        output += next;
        position += 1;
      } else {
        inSingleQuote = !inSingleQuote;
      }

      continue;
    }

    if (char === "\"" && !inSingleQuote) {
      inDoubleQuote = !inDoubleQuote;
      output += char;
      continue;
    }

    if (char === "?" && !inSingleQuote && !inDoubleQuote) {
      index += 1;
      output += `$${index}`;
      continue;
    }

    output += char;
  }

  return output;
}

function normalizeRows(rows, fields) {
  return rows.map((row) => {
    const normalized = {};

    for (const field of fields) {
      const value = row[field.name];

      normalized[field.name] =
        typeof value === "string" && numericTypeIds.has(field.dataTypeID) && /^-?\d+(\.\d+)?$/.test(value)
          ? Number(value)
          : value;
    }

    return normalized;
  });
}

function splitCommaList(value) {
  return value
    .split(",")
    .map((entry) => entry.trim())
    .filter(Boolean);
}

function quoteIdentifier(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function unquoteIdentifier(value) {
  const trimmed = value.trim();

  return trimmed.startsWith('"') && trimmed.endsWith('"')
    ? trimmed.slice(1, -1).replaceAll('""', '"')
    : trimmed;
}
